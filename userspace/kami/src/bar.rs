/// How many characters fit in a bar `width` pixels wide.
pub fn columns(width: usize) -> usize {
    width.saturating_sub(2 * SCALE * 2) / CELL_W
}

/// Render `text` into `width` x [`HEIGHT`] pixels of 0/1 coverage (row-major),
/// clipped at the right edge. `width` must be at least one cell.
pub fn render(text: &str, width: usize) -> Vec<u8> {
    let mut px = vec![0u8; width * HEIGHT];
    let top = (HEIGHT - GLYPH_H) / 2;
    for (i, c) in text.chars().take(columns(width)).enumerate() {
        let g = glyph(c);
        let x0 = 2 * SCALE + i * CELL_W;
        for (row, bits) in g.iter().enumerate() {
            for col in 0..5 {
                if bits & (0x10 >> col) == 0 {
                    continue;
                }
                for dy in 0..SCALE {
                    for dx in 0..SCALE {
                        let (x, y) = (x0 + col * SCALE + dx, top + row * SCALE + dy);
                        if x < width {
                            px[y * width + x] = 1;
                        }
                    }
                }
            }
        }
    }
    px
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The glyph as text, so a wrong bit shows up in a failing diff.
    fn art(c: char) -> String {
        glyph(c).iter().map(|r| (0..5).map(|b| if r & (0x10 >> b) != 0 { '#' } else { '.' }).collect::<String>()).collect::<Vec<_>>().join("\n")
    }

    #[test]
    fn a_few_glyphs_look_right() {
        assert_eq!(art('A'), ".###.\n#...#\n#...#\n#####\n#...#\n#...#\n#...#");
        assert_eq!(art('K'), "#...#\n#..#.\n#.#..\n##...\n#.#..\n#..#.\n#...#");
        assert_eq!(art('Q'), ".###.\n#...#\n#...#\n#...#\n#.#.#\n#..#.\n.##.#");
        assert_eq!(art('/'), "....#\n....#\n...#.\n..#..\n.#...\n#....\n#....");
    }

    #[test]
    fn every_status_character_is_defined() {
        let boxed = art('\u{1}');
        for c in "NORMAL  J/K D/U GG G SCROLL F LINKS I TYPE H/L BACK/FWD CTRL-Q QUIT INSERT ESC TO LEAVE 0123456789.:/-_".chars() {
            assert!(c == ' ' || art(c) != boxed, "{c:?} is the missing-glyph box");
        }
    }

    #[test]
    fn render_clips_and_fits() {
        let w = 200;
        assert!(columns(w) > 5);
        let px = render("HELLO WORLD THIS IS FAR TOO LONG FOR THE BAR", w);
        assert_eq!(px.len(), w * HEIGHT);
        assert!(px.iter().any(|&p| p == 1));
        // Nothing drawn in the last column of the bar.
        assert!((0..HEIGHT).all(|y| px[y * w + w - 1] == 0));
    }
}

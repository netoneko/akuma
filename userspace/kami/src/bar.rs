//! The status bar kami draws itself, on the framebuffer under the page.
//!
//! It lives outside the page on purpose: a page that is blank, still loading,
//! wedged, or whose system fonts did not load has no DOM overlay to show, and
//! those are exactly the moments the bar is for. It uses a built-in 5x7 bitmap
//! font (upper case, digits, punctuation), scaled up, so it needs no font
//! file and no Chromium.

/// Pixel rows reserved at the bottom of the screen for the bar.
pub const HEIGHT: usize = 24;

const SCALE: usize = 2;
const CELL_W: usize = 6 * SCALE; // 5 columns + 1 spacing
const GLYPH_H: usize = 7 * SCALE;

/// 5x7 glyphs, one byte per row, bit 4 = leftmost column. Lower case is drawn

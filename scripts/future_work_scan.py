#!/usr/bin/env python3
"""Regenerate the inventory half of `proposals/FUTURE_WORK.md`.

Greps every Markdown file, and the `TODO`/`FIXME` comments in Rust files, for the words authors use when they leave
something undone ("still open", "future work", "unresolved", "deferred", "follow-up", ...), and rewrites the block
between the GENERATED markers. Everything it lists is **unverified**: a hit is a sentence someone wrote, not a fact that
the work is still outstanding. A hit that also says fixed/done/resolved/closed (or is struck through) is flagged
`maybe resolved`, which is a hint for the person verifying and nothing more. Precision is grep-level: some hits are the
word used in another sense ("deferred drop"). Recall is also grep-level: work described without these words is missed.

    scripts/future_work_scan.py            # rewrite the generated block
    scripts/future_work_scan.py --check    # exit 1 if the checked-in block is stale
"""
import collections
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, "proposals", "FUTURE_WORK.md")
BEGIN, END = "<!-- BEGIN GENERATED -->", "<!-- END GENERATED -->"
SKIP_DIRS = {"target", ".git", "node_modules", "overlays", ".claude"}
SELF = {os.path.join("proposals", "FUTURE_WORK.md"), os.path.join("scripts", "future_work_scan.py")}

MARK = re.compile(
    r"(still open|\bopen:|\*\*open\b|not done|future work|unresolved|\bTODO\b|\bFIXME\b|follow-?up|\bdeferred\b|known gap"
    r"|not yet (?:done|implemented|fixed|handled)|open question|remaining work|next steps?|left open|not fixed|unfixed"
    r"|outstanding)",
    re.I,
)
DONE = re.compile(r"(~~|\bfixed\b|\bdone\b|\bresolved\b|✅|\bclosed\b|\blanded\b|\bshipped\b)", re.I)


def scan():
    hits = collections.defaultdict(list)
    for dp, dn, fn in os.walk(ROOT):
        dn[:] = sorted(d for d in dn if d not in SKIP_DIRS)
        for f in sorted(fn):
            if not f.endswith((".md", ".rs")):
                continue
            path = os.path.join(dp, f)
            rel = os.path.relpath(path, ROOT)
            if rel in SELF:
                continue
            try:
                lines = open(path, encoding="utf-8").read().split("\n")
            except (OSError, UnicodeDecodeError):
                continue
            for n, line in enumerate(lines, 1):
                if not MARK.search(line):
                    continue
                if f.endswith(".rs") and not re.search(r"\b(TODO|FIXME)\b", line):
                    continue
                hits[rel].append((n, line.strip(), bool(DONE.search(line))))
    return hits


def clean(text, width=170):
    text = text.replace("`", "'").replace("<", "&lt;").replace(">", "&gt;").replace("|", "/")
    text = re.sub(r"\s+", " ", text)
    return text if len(text) <= width else text[: width - 1] + "…"


def render(hits):
    live = {k: v for k, v in hits.items() if not k.startswith("docs/archive/")}
    arch = {k: v for k, v in hits.items() if k.startswith("docs/archive/")}
    total = sum(len(v) for v in hits.values())
    maybe = sum(1 for v in hits.values() for h in v if h[2])
    out = [BEGIN, "",
           f"Generated by `scripts/future_work_scan.py`: **{total} hits in {len(hits)} files** "
           f"({sum(len(v) for v in live.values())} outside `docs/archive`, {sum(len(v) for v in arch.values())} inside; "
           f"{maybe} also say fixed/done/resolved and are flagged `maybe resolved`). All **unverified**.", ""]
    for title, group, fold in (("Live docs, runbooks, scripts and code comments", live, False), ("`docs/archive`", arch, True)):
        out += [f"## Inventory: {title}", ""]
        for rel in sorted(group):
            rows = group[rel]
            head = f"{rel} ({len(rows)})"
            if fold:
                out += [f"<details><summary>{head}</summary>", ""]
            else:
                out += [f"### {head}", ""]
            for n, text, done in rows:
                out.append(f"- L{n}: {clean(text)}{'  _(maybe resolved)_' if done else ''}")
            out += ["", "</details>", ""] if fold else [""]
    out.append(END)
    return "\n".join(out) + "\n"


def main(argv):
    block = render(scan())
    doc = open(TARGET, encoding="utf-8").read()
    i, j = doc.index(BEGIN), doc.index(END) + len(END)
    new = doc[:i] + block.rstrip("\n") + doc[j:]
    if "--check" in argv:
        if new != doc:
            print("future_work_scan: FUTURE_WORK.md inventory is stale; run scripts/future_work_scan.py")
            return 1
        print("future_work_scan: ok")
        return 0
    open(TARGET, "w", encoding="utf-8").write(new)
    print(f"future_work_scan: wrote {os.path.relpath(TARGET, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

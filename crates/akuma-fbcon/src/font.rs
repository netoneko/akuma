/// The eight rows of `byte`'s glyph.
#[must_use]
pub const fn glyph(byte: u8) -> &'static [u8; HEIGHT] {
    if byte < FIRST || byte > LAST {
        return &REPLACEMENT;
    }
    &GLYPHS[(byte - FIRST) as usize]
}

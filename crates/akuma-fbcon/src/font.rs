//! An 8x8 bitmap font covering printable ASCII, drawn for this crate.
//!
//! One byte per row, most significant bit leftmost, eight rows per glyph, in
//! code-point order from `0x20` (space) through `0x7E` (`~`). A glyph outside
//! that range renders as [`REPLACEMENT`] rather than as whatever byte follows
//! the table — a console that silently draws garbage for a stray byte is worse
//! than one that draws a visible box.
//!
//! Row 7 is blank on nearly every glyph so consecutive lines of text do not
//! touch; the descenders (`g j p q y`) use it, which is why they look right
//! only when the line pitch is the full eight rows.
//!
//! 8x8 rather than the more usual 8x16 because the console scales integrally at
//! render time ([`crate::Console::scale`]): one small font covers a 1024x768
//! monitor at 2x and a 4K television at 5x, and there is no second table to
//! keep in agreement with the first.

/// Pixels across one glyph.
pub const WIDTH: usize = 8;
/// Pixels down one glyph.
pub const HEIGHT: usize = 8;
/// First code point in [`GLYPHS`].
pub const FIRST: u8 = 0x20;
/// Last code point in [`GLYPHS`].
pub const LAST: u8 = 0x7E;

/// Drawn for any byte outside `FIRST..=LAST`: a hollow box.
pub const REPLACEMENT: [u8; HEIGHT] = [
    0b0111_1110,
    0b0100_0010,
    0b0100_0010,
    0b0100_0010,
    0b0100_0010,
    0b0100_0010,
    0b0111_1110,
    0b0000_0000,
];


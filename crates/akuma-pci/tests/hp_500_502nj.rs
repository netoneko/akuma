#[test]
fn config_address_word_matches_the_hardware_encoding() {
    // 00:14.0, offset 0 -> enable | bus 0 | dev 0x14 | func 0.
    assert_eq!(Address::new(0, 0x14, 0).config_address(0), 0x8000_a000);
    // 03:00.0, offset 0x10 (BAR0).
    assert_eq!(Address::new(3, 0, 0).config_address(0x10), 0x8003_0010);
    // The offset is aligned down to a dword.
    assert_eq!(
        Address::new(0, 0x1a, 0).config_address(0x0e),
        Address::new(0, 0x1a, 0).config_address(0x0c)
    );
}

#[test]
fn xhci_header_and_bar() {
    let h = Header::parse(XHCI).expect("xhci header");
    assert_eq!(h.vendor_id, 0x8086);
    assert_eq!(h.device_id, 0x8c31);
    assert!(h.is_class(class::SERIAL_BUS, subclass::USB));
    assert_eq!(h.prog_if, usb_prog_if::XHCI);
    assert!(h.is_xhci());
    assert!(!h.is_bridge());
    assert!(!h.multifunction);
    assert_eq!(h.subsystem_vendor_id, 0x103c);
    assert_eq!(h.capabilities_pointer, 0x70);
    assert_eq!(h.interrupt_pin, 1);

    let bars = decode_bars(&raw_bars(XHCI).unwrap());
    match bars[0] {
        Some(Bar::Memory { address, is_64bit, prefetchable, .. }) => {
            assert_eq!(address, 0xf720_0000);
            assert!(is_64bit);
            assert!(!prefetchable);
        }
        other => panic!("BAR0 should be 64-bit memory, got {other:?}"),
    }
    assert!(bars[1].is_none(), "BAR1 is consumed by the 64-bit BAR0");
    assert!(bars[2..].iter().all(Option::is_none));
}

#[test]
fn xhci_capability_chain_is_pm_then_msi() {
    let h = Header::parse(XHCI).unwrap();
    let caps: std::vec::Vec<_> = capabilities(XHCI, h.capabilities_pointer).collect();
    assert_eq!(caps.len(), 2);
    assert_eq!(caps[0].id, capability_id::POWER_MANAGEMENT);
    assert_eq!(caps[0].offset, 0x70);
    assert_eq!(caps[1].id, capability_id::MSI);
    assert_eq!(caps[1].offset, 0x80);
}

#[test]
fn ehci_is_a_32bit_memory_bar() {
    let h = Header::parse(EHCI).expect("ehci header");
    assert!(h.is_ehci());
    assert_eq!(h.capabilities_pointer, 0x50);

    let bars = decode_bars(&raw_bars(EHCI).unwrap());
    match bars[0] {
        Some(Bar::Memory { address, is_64bit, .. }) => {
            assert_eq!(address, 0xf721_8000);
            assert!(!is_64bit);
        }
        other => panic!("expected 32-bit memory BAR, got {other:?}"),
    }
}

#[test]
fn rtl8168_has_an_io_bar_a_64bit_mmio_bar_and_a_prefetchable_one() {
    let h = Header::parse(RTL8168).expect("rtl8168 header");
    assert_eq!(h.vendor_id, 0x10ec);
    assert_eq!(h.device_id, 0x8168);
    assert!(h.is_ethernet());
    assert_eq!(h.revision, 0x0c);

    let bars = decode_bars(&raw_bars(RTL8168).unwrap());
    assert_eq!(bars[0], Some(Bar::Io { port: 0xd000, size: 0 }));
    assert_eq!(
        bars[2],
        Some(Bar::Memory { address: 0xf710_0000, size: 0, prefetchable: false, is_64bit: true })
    );
    assert_eq!(
        bars[4],
        Some(Bar::Memory { address: 0xf210_0000, size: 0, prefetchable: true, is_64bit: true })
    );
    // Slots 1, 3, 5 are the high halves / empty.
    assert!(bars[1].is_none() && bars[3].is_none() && bars[5].is_none());
}

#[test]
fn rtl8168_capability_chain() {
    let h = Header::parse(RTL8168).unwrap();
    let ids: std::vec::Vec<u8> = capabilities(RTL8168, h.capabilities_pointer).map(|c| c.id).collect();
    assert_eq!(
        ids,
        [
            capability_id::POWER_MANAGEMENT,
            capability_id::MSI,
            capability_id::PCI_EXPRESS,
            capability_id::MSI_X,
            capability_id::VPD,
        ]
    );
}

#[test]
fn bar_size_arithmetic() {
    // A 16 KiB memory BAR probes back as 0xFFFFC000.
    assert_eq!(bar_size(0xffff_c000, 0, false, false), 16 * 1024);
    // A 256-byte I/O BAR probes back as 0xFFFFFF01 (bit 0 is the I/O marker).
    assert_eq!(bar_size(0xffff_ff01, 0, true, false), 256);
    // A 64-bit BAR: low 0x00000000, high 0xFFFFFFFF -> 4 GiB.
    assert_eq!(bar_size(0x0000_0000, 0xffff_ffff, false, true), 4 * 1024 * 1024 * 1024);
    // An unimplemented BAR reads back 0.
    assert_eq!(bar_size(0, 0, false, false), 0);
}

#[test]
fn an_absent_device_and_a_short_buffer_are_none() {
    assert!(Header::parse(&[0xff; 64]).is_none());
    assert!(Header::parse(&[0x86, 0x80, 0x31, 0x8c]).is_none());
}

#[test]
fn a_capability_pointer_loop_terminates() {
    // Craft config space whose only capability points back at itself.
    let mut cfg = [0u8; 256];
    cfg[0] = 0x86;
    cfg[1] = 0x80;
    cfg[0x06] = 1 << 4; // status: has capability list
    cfg[0x34] = 0x40;
    cfg[0x40] = capability_id::VENDOR;
    cfg[0x41] = 0x40; // next -> itself
    let n = capabilities(&cfg, 0x40).count();
    assert_eq!(n, 16, "bounded by the 16-iteration budget");
}
